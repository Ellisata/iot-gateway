-- 设备的「扫描来源身份签名」列。
--
-- 背景：扫描结果一键建设备时，唯一能查重的只有 device.name（有唯一索引）。
-- 用户只要把设备名改掉再扫一遍，就能为同一个地址建出第二行 —— 而网关会为
-- 每一行各开一份采集任务，重复占用 PLC 有限的连接槽位，并把同一份数据推两遍。
--
-- 为什么不在数据库层直接加唯一约束：
--   同一个地址上多台设备是合法且常见的（Modbus TCP 串口服务器后面挂多个从站
--   靠站号区分、多通道串口服务器的不同端口、同一台 PLC 同时开 S7 与 Modbus）。
--   约束只能建在「协议+主机+端口+站号」四元组上，而这个四元组来自插件给的
--   扫描结果，手工新建与 Excel 导入的设备根本没有它（网关侧要从 protocol_json
--   里认出地址，得先有一套跨协议的键名约定，那些表单是插件自己声明的）。
--   于是空值会互相相撞，约束就得带 NULL 语义 —— 收益远小于代价。
--   所以这一列只作为**软提示**的依据：建库时比中了就报给用户确认，不拦。
--
-- 空串 = 这行不是扫描建的（或建成后配置被改过），不参与比对。
ALTER TABLE device ADD COLUMN scan_identity TEXT NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_device_scan_identity ON device(scan_identity);
